#!/usr/bin/env python3
"""Human-authored turn extraction for the pre-registered correction-survival test.

This module exists because the stage 1 denominator was polluted. "User text
turns" as the first build counted them includes three kinds of record that the
human did not write, all of which arrive as ``type: "user"``:

- **tool results**, which are 93.2% of user records and were already excluded;
- **peer and subagent hand-backs**, delivered into the session as a user turn
  wrapped in ``<agent-message from="...">``, which are model output;
- **harness markers**, of which ``[Request interrupted by user for tool use]``
  is the common one -- a record *about* the human rather than *by* them.

In the positive-control session ``6d7b783e`` that is 3 of 6 turns, so the
pollution is not a rounding error at the session scale where a correction has
to be found. A correction rate must be counted against human-authored turns
only, per the pre-registration's stage 1 section.

The extraction lives here rather than in the detector so that the detector,
the seed sampler and the candidate builder all count the same denominator by
construction instead of by three copies agreeing.
"""

from __future__ import annotations

import glob
import json
import os
import re
from pathlib import Path
from typing import Dict, Iterator, List, Optional

# Frame boundary: claim-shaped headings became mandatory in agent-session-rollup
# commit 8fcd12b on this date, so notes before it were written by a different
# prompt and are not measuring the same pipeline.
FRAME_START_DATE = '2026-09-21'

# Envelopes that make a `type: "user"` record something other than the human
# typing, grouped by what produced them so the denominator can be reported with
# its subtractions named instead of lumped into one skip.
#
# This list is longer than the first fix because the first fix was checked by
# reading its own output: a 60-turn sample drawn after excluding only hand-backs
# and interrupt markers still contained six harness continuation summaries, two
# `!` shell passthroughs, a task notification, a safety-classifier notice and
# four benchmark probes - 13 of 60. Every category below was found by reading
# sampled turns, not by predicting them, which is why the sample is drawn and
# committed before it is labelled.
NON_HUMAN_ENVELOPES = {
    # A subagent's or peer's report, delivered into the session as a user turn.
    'agent_handback': (
        '<agent-message from=',
        'Another Claude session sent a message:',
        '[Subagent hand-back]',
        '[SYSTEM NOTIFICATION - NOT USER INPUT]',
    ),
    # The harness's own compaction summary of an earlier context window. This is
    # model output about the conversation, and at 15% of the first sample it was
    # the single largest contaminant. It is also the artifact the paper's
    # prose-only arm turned out to be half-composed of, so counting it as a
    # human turn would import that contamination into this test as well.
    'continuation_summary': (
        'This session is being continued from a previous conversation that ran out of context',
        'The summary below covers the earlier portion of the conversation',
    ),
    # The `!` passthrough. The command line is typed by the human but is a
    # command rather than prose, and the captured stdout/stderr is machine text.
    'bash_passthrough': (
        '<bash-input>',
        '<bash-stdout>',
        '<bash-stderr>',
        '<local-command-stdout>',
        '<local-command-stderr>',
        '<command-message>',
        '<command-name>',
        'Caveat: The messages below were generated by the user while running local commands',
    ),
    # Background-task lifecycle notices.
    'task_notification': (
        '<task-notification>',
    ),
    # Harness notices addressed to the assistant about its own last turn, and
    # injected state changes it is told about rather than asked for.
    'harness_notice': (
        'Your response above was stopped by a safety classifier',
        '[Request interrupted by user for tool use]',
        '[Request interrupted by user]',
        'A session-scoped Stop hook is now active with condition',
        'Loop iteration:',
    ),
    # Attachment metadata the harness writes in place of the attachment.
    'attachment_metadata': (
        '[Image: original ',
        '[Pasted text ',
    ),
    # Prompts injected by this project's own measurement harnesses, in
    # scripts/answer_speed/*_bench.py and the rollup probe runners. The corpus
    # under test contains the instrumentation that tested it, and a benchmark
    # prompt is not the human's corrective register by construction.
    'bench_probe': (
        'Answer in one sentence, under 25 words. No preamble.',
        'Reply with exactly',
        'Reply with the single word',
        'Answer from your tool list only',
    ),
}

# Harness markers that are a record *about* the human, not *by* them. A turn
# whose entire content is one of these carries no authored text.
HARNESS_MARKERS = (
    '[Request interrupted by user for tool use]',
    '[Request interrupted by user]',
    'API Error',
)

_SYSTEM_REMINDER = re.compile(r'<system-reminder>.*?</system-reminder>', re.DOTALL)


def strip_system_reminders(text: str) -> str:
    """Remove system-reminder blocks, which are injected rather than authored."""
    return _SYSTEM_REMINDER.sub('', text).strip()


def is_tool_result(record: Dict) -> bool:
    """True if this user record is a tool result rather than authored text."""
    content = record.get('message', {}).get('content', [])
    if not isinstance(content, list):
        return False
    return any(
        isinstance(block, dict) and block.get('type') == 'tool_result'
        for block in content
    )


def extract_text(record: Dict) -> str:
    """Concatenate the text blocks of a record, system-reminders removed."""
    content = record.get('message', {}).get('content', '')

    if isinstance(content, str):
        return strip_system_reminders(content)

    if not isinstance(content, list):
        return ''

    parts = []
    for block in content:
        if isinstance(block, dict) and block.get('type') == 'text':
            text = strip_system_reminders(block.get('text', ''))
            if text:
                parts.append(text)
    return ' '.join(parts)


def classify_user_record(record: Dict) -> str:
    """Classify a `type: "user"` record.

    Returns one of ``human``, ``tool_result``, ``reminder_only``,
    ``harness_marker``, ``non_human_envelope``, ``empty``. Every exclusion is
    named rather than collapsed into a single skip, so the denominator can be
    reported with its subtractions shown instead of asserted.
    """
    if record.get('type') != 'user':
        return 'not_user'

    if is_tool_result(record):
        return 'tool_result'

    raw = record.get('message', {}).get('content', '')
    had_raw_text = bool(raw if isinstance(raw, str) else raw)

    text = extract_text(record)
    if not text:
        return 'reminder_only' if had_raw_text else 'empty'

    stripped = text.strip()
    if stripped in HARNESS_MARKERS or any(
        stripped.startswith(m) and len(stripped) < len(m) + 8 for m in HARNESS_MARKERS
    ):
        return 'harness_marker'

    # The envelope is looked for in the opening window rather than anywhere in
    # the text, so that a human turn *quoting* one of these markers - which is
    # exactly what a turn complaining about a continuation summary looks like -
    # is not thrown away as being one. Sole exception: the passthrough and
    # notification tags are structural and are matched anywhere, because they
    # wrap the whole record.
    window = text[:400]
    for category, envelopes in NON_HUMAN_ENVELOPES.items():
        anywhere = category in ('bash_passthrough', 'task_notification')
        haystack = text if anywhere else window
        if any(envelope in haystack for envelope in envelopes):
            return category

    return 'human'


def human_turns(transcript: List[Dict]) -> Iterator[tuple]:
    """Yield ``(record_index, text)`` for every human-authored turn."""
    for index, record in enumerate(transcript):
        if record.get('type') != 'user':
            continue
        if classify_user_record(record) == 'human':
            yield index, extract_text(record)


def exclusion_counts(transcript: List[Dict]) -> Dict[str, int]:
    """Count every user record by classification, for the audit trail."""
    counts: Dict[str, int] = {}
    for record in transcript:
        if record.get('type') != 'user':
            continue
        kind = classify_user_record(record)
        counts[kind] = counts.get(kind, 0) + 1
    return counts


def load_transcript(path: str) -> List[Dict]:
    """Load a JSONL transcript, skipping records that do not parse."""
    records = []
    with open(path, 'r', encoding='utf-8') as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return records


def load_frontmatter(md_path: str) -> Dict[str, str]:
    """Parse the flat key/value subset of a note's YAML frontmatter."""
    with open(md_path, 'r', encoding='utf-8') as handle:
        content = handle.read()

    if not content.startswith('---\n'):
        return {}

    end = content.find('\n---\n', 4)
    if end == -1:
        return {}

    result = {}
    for line in content[4:end].split('\n'):
        if ':' in line and not line.startswith((' ', '-', '\t')):
            key, value = line.split(':', 1)
            result[key.strip()] = value.strip()
    return result


def find_transcript(session_id: str, projects_dir: str) -> Optional[str]:
    """Locate a transcript by full session id."""
    matches = glob.glob(os.path.join(projects_dir, '*', f'{session_id}.jsonl'))
    return matches[0] if matches else None


def resolve_notes(session_id: str, sessions_dir: str) -> List[str]:
    """Return every rollup note a session produced, resolved by session id.

    Resolution is by id prefix and never by filename, because the pipeline
    rewrites a note's filename when a session is resumed, so a filename is not
    a stable key. The return is a **list** rather than a single path: a resumed
    session legitimately has several notes, and the first build's choice to skip
    those sessions dropped the cases where a late correction gets written into a
    note at all -- biasing the result toward the hypothesis by construction.
    A correction is scored against the union of these.
    """
    prefix = session_id.split('-')[0][:8]
    return sorted(glob.glob(os.path.join(sessions_dir, f'*_{prefix}_*.md')))


def frame_sessions(sessions_dir: str, projects_dir: str) -> List[Dict]:
    """Every session in the pre-registered frame, with its notes and transcript.

    A session qualifies on mechanical criteria only: a note dated on or after
    FRAME_START_DATE, a full `session_id` in that note's frontmatter, a readable
    transcript at the path the id resolves to, and at least one resolvable note.
    """
    seen_ids = set()
    frame = []

    for note_path in sorted(glob.glob(os.path.join(sessions_dir, '*.md'))):
        frontmatter = load_frontmatter(note_path)

        if frontmatter.get('date', '') < FRAME_START_DATE:
            continue

        session_id = frontmatter.get('session_id', '').strip()
        if not session_id or '-' not in session_id:
            # `recap_session` stubs carry no rollup body, so there is nothing to
            # score; they are excluded as having no note rather than silently.
            continue

        if session_id in seen_ids:
            continue
        seen_ids.add(session_id)

        transcript_path = find_transcript(session_id, projects_dir)
        if not transcript_path:
            continue

        notes = resolve_notes(session_id, sessions_dir)
        if not notes:
            raise RuntimeError(
                f'SCRIPT ERROR: no rollup note resolves for session_id {session_id}; '
                'a zero-match resolution halts the run per the pre-registration'
            )

        frame.append({
            'session_id': session_id,
            'transcript_path': transcript_path,
            'note_paths': notes,
            'note_count': len(notes),
        })

    return frame
